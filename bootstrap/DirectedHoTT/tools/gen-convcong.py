#!/usr/bin/env python3
# Generates Algorithm/ConvCong.agda: one conversion congruence per term
# former, `a₁ ≅ b₁ → … → C a₁ … ≅ C b₁ …`, from `Spec/Syntax`'s RTm
# constructors and `Spec/Typing`'s ξ-rules (one per argument position).
# Usage (from DirectedHoTT/): python3 tools/gen-convcong.py > Algorithm/ConvCong.agda
import re
syn=open('Spec/Syntax.agda').read()
blk=syn[syn.index('data RTm where'):syn.index('data Thin')]
cons=[]
for l in blk.split('\n'):
    m=re.match(r'^  (\S+(?: \S+)*?) +: ∀ \{Γ\} → (.*)$',l)
    if not m: continue
    names=m.group(1).split(); ty=m.group(2)
    parts=[p.strip() for p in re.split(r' → ',ty)]
    args=parts[:-1]
    for n in names: cons.append((n,args))
ty=open('Spec/Typing.agda').read()
tblk=ty[ty.index('data _⟶_'):ty.index('data _⟶ᵀ_')]
rules=re.findall(r'^  (ξ-\S+)\s*:\s*(.*?)(?=^  \S|\Z)', tblk, flags=re.S|re.M)
pos={}
for name,t in rules:
    t=' '.join(t.split())
    m=re.search(r'→ (\S+) ⟶ (\S+) → (.*) ⟶ (.*)$', t)
    a,_,lhs,_=m.groups()
    toks=lhs.split(); c=toks[0]; i=toks[1:].index(a)
    pos[(c,i)]=name
def ctx(a):
    m=re.match(r'RTm (.*)$',a); g=m.group(1)
    return g.replace('Γ','Γ')
out=["""-- SPDX-License-Identifier: AGPL-3.0-or-later
-- Copyright (C) 2025-2026 Jonas Claesson

------------------------------------------------------------------------
-- OCP-0009 · dHoTT — conversion is a CONGRUENCE, former by former.
--
-- ⚠ GENERATED by tools/gen-convcong.py from `Spec/Syntax`'s term formers
--   and `Spec/Typing`'s ξ-rules (one per argument position); each lemma is
--   `ConvLazy.cong≅` at each position, chained.  Regenerate when a former
--   or a ξ-rule is added.
--
-- `--safe`, ZERO axioms.
------------------------------------------------------------------------

{-# OPTIONS --safe #-}
module DirectedHoTT.Algorithm.ConvCong where
open import Agda.Builtin.Nat using ( Nat )
open import DirectedHoTT.Spec.Syntax
open import DirectedHoTT.Spec.Typing hiding ( _×_; _,,_ )
open import DirectedHoTT.Algorithm.ConvLazy using ( cong≅ )

private
  variable
    Γ : Cx
"""]
for c,args in cons:
    tm=[i for i,a in enumerate(args) if a.startswith('RTm')]
    if not tm or c=='ref': continue
    if any((c,j) not in pos for j in range(len(tm))):
        # positions indexed among RTm args only
        pass
    xs=[f"a{i}" for i in range(len(args))]; ys=[f"b{i}" for i in range(len(args))]
    binds=[]
    for i,a in enumerate(args):
        if a.startswith('RTm'):
            binds.append(f"{{a{i} b{i} : {a}}}")
        else:
            binds.append(f"{{a{i} : {a}}}")
    prem=" → ".join(f"a{i} ≅ b{i}" for i in tm)
    def term(vals): return f"{c} {' '.join(vals)}"
    lhs=term(xs)
    rhsv=[ys[i] if args[i].startswith('RTm') else xs[i] for i in range(len(args))]
    sig=f"≅{c} : {' '.join(binds)} → {prem} → {lhs} ≅ {term(rhsv)}"
    es=[f"e{i}" for i in tm]
    # chain: change position by position (left to right)
    steps=[]
    for k,i in enumerate(tm):
        cur=[ (ys[j] if (args[j].startswith('RTm') and j<i) else xs[j]) for j in range(len(args))]
        cur[i]='x'
        rule=pos[(c,k)]
        steps.append(f"cong≅ (λ x → {c} {' '.join(cur)}) {rule} e{i}")
    body=steps[-1]
    for st in reversed(steps[:-1]):
        body=f"ctrn ({st}) ({body})"
    out.append(sig)
    imps=" ".join(("{a%d = a%d} {b%d = b%d}" % (i,i,i,i)) if args[i].startswith("RTm") else ("{a%d = a%d}" % (i,i)) for i in range(len(args)))
    out.append(f"≅{c} {imps} {' '.join(es)} = {body}")
    out.append("")
print("\n".join(out))
