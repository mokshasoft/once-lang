#!/usr/bin/env bash
# backstop.sh — the island backstop: type-check EVERY module except the recorded
# red islands (scripts/backstop.islands), so nothing off the apex rots silently
# and a new module is checked from the day it lands. Generates
# EverythingFiltered.agda (untracked) and checks it under the safe wrapper.
#
# Usage (from formal/):  scripts/backstop.sh [--generate-only]
set -euo pipefail
cd "$(dirname "$0")/.."

islands=scripts/backstop.islands
mapfile -t skip < <(sed 's/#.*//; s/[[:space:]]*$//' "$islands" | grep -v '^$')
declare -A is=()
for m in "${skip[@]}"; do
  f=${m//.//}.agda
  [[ -f $f ]] || { echo "backstop: $islands lists $m, which no longer exists — delete the line"; exit 1; }
  is[$m]=1
done

out=EverythingFiltered.agda
{ echo "-- GENERATED by scripts/backstop.sh — do not edit."
  echo "module EverythingFiltered where"
  find Once -name '*.agda' | LC_ALL=C sort | sed 's|/|.|g; s|\.agda$||' |
    while read -r m; do [[ -n ${is[$m]:-} ]] || echo "import $m"; done
} > "$out"
n=$(grep -c '^import ' "$out")
echo "backstop: $n modules, ${#skip[@]} islands skipped"
[[ ${1:-} == --generate-only ]] && exit 0
exec scripts/agda-safe.sh agda MODULE="$out"
